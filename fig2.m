    'FontName', fontName, 'FontSize', regionFontSize, 'FontWeight', 'bold');
text(axD, 3.55, 120, '$P_l$', 'Interpreter', 'latex', ...
    'FontName', fontName, 'FontSize', regionFontSize, 'FontWeight', 'bold');
text(axD, 4.35, 38, '$F_l$', 'Interpreter', 'latex', ...
    'FontName', fontName, 'FontSize', regionFontSize, 'FontWeight', 'bold');

text(axD, 4.72, 325, '$\eta=0$', ...
    'Interpreter', 'latex', ...
