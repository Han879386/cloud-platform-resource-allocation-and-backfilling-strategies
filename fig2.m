%% Local functions
function Z = classifyCoverage(V, G, price, transitionWidth, gamma0, gammaF)
%CLASSIFYCOVERAGE Classify empty, partial, and full market coverage.
%   1 = empty market, 2 = partial coverage, 3 = full coverage.

    Z = ones(size(V));

    partialRegion = ...
        (V >= price & V <= price + transitionWidth & G >= 0 & G < gamma0) | ...
        (V >= price + transitionWidth & G > gammaF & G < gamma0);

    fullRegion = ...
        (V >= price + transitionWidth & G >= 0 & G <= gammaF);

    Z(partialRegion) = 2;
    Z(fullRegion) = 3;
end

function formatAxes(ax, fontName, tickSize, labelSize, xLimits, yLimits, xText, yText)
%FORMATAXES Apply a common publication-ready axes style.

    xlabel(ax, xText, ...
        'Interpreter', 'latex', ...
        'FontName', fontName, ...
        'FontSize', labelSize);

    ylabel(ax, yText, ...
        'Interpreter', 'latex', ...
        'FontName', fontName, ...
        'FontSize', labelSize);

    xlim(ax, xLimits);
    ylim(ax, yLimits);

    set(ax, ...
        'FontName', fontName, ...
        'FontSize', tickSize, ...
        'LineWidth', 0.9, ...
        'TickDir', 'out', ...
        'TickLength', [0.018 0.018], ...
        'Layer', 'top', ...
        'Box', 'on');
end

function drawBoundaryShift(ax, xArrow, yStart, yTarget, color, direction)
%DRAWBOUNDARYSHIFT Draw a compact directional marker between boundaries.

    arrowScale = 0.72;
    yEnd = yStart + arrowScale * (yTarget - yStart);

    plot(ax, [xArrow xArrow], [yStart yEnd], ...
        '-', ...
        'Color', color, ...
        'LineWidth', 1.15, ...
        'HandleVisibility', 'off');

    if strcmpi(direction, 'up')
        marker = '^';
    else
        marker = 'v';
    end

    plot(ax, xArrow, yEnd, marker, ...
        'MarkerFaceColor', color, ...
        'MarkerEdgeColor', color, ...
        'MarkerSize', 5.0, ...
        'HandleVisibility', 'off');
end
