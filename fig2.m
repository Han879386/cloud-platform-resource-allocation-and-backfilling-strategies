%% Figure 2: Market classification before and after operational integration
% 2-by-2 publication-ready MATLAB figure.
% Optimized for insertion into Word at approximately 110 mm width.
%
% Panels:
%   (a) Pre-integration high-tier market
%   (b) Pre-integration low-tier market
%   (c) Post-integration high-tier market under eta = 0 and eta = etaBar
%   (d) Post-integration low-tier market under eta = 0 and eta = etaBar
%
% NOTE:
%   The parameter-assignment line previously shown below the figure
%   has been removed to maximize the usable plotting area.

clearvars;
clc;
close all;

%% 1. Common calibration
fontName = 'Times New Roman';

N     = 100;
alpha = 0.30;
NH    = alpha * N;
NL    = (1 - alpha) * N;

tH = 1.0;
tL = 1.0;
pH = 2.0;
pL = 1.5;

SG     = 50;            % post-integration high-tier capacity pool
SLPre  = 50;            % low-tier capacity of each pre-integration platform
SC     = 2 * SLPre;     % pooled low-tier capacity after integration

etaBar = 0.30;          % fixed-ratio backfilling intensity
WbarH  = 0.10;          % maximum waiting time allowed by the high-tier SLA
bH     = 1 / WbarH;     %#ok<NASGU> % minimum SLA capacity reserve

nGrid = 600;

%% 2. Publication settings for 110-mm Word width
emptyColor    = [0.88 0.60 0.60];
partialColor  = [0.96 0.84 0.44];
fullColor     = [0.55 0.75 0.93];
regionMap     = [emptyColor; partialColor; fullColor];

eta0Color     = [0.10 0.32 0.70];
etaBarColor   = [0.82 0.22 0.14];
boundaryColor = [0.12 0.12 0.12];

% These are the FINAL physical font sizes when the figure is inserted
% into Word at 110 mm width without additional scaling.
axisFontSize   = 8.2;
labelFontSize  = 9.5;
titleFontSize  = 8.8;
legendFontSize = 6.4;
regionFontSize = 10.5;
etaFontSize    = 7.8;

lineWidth      = 1.35;

% Final figure width = 110 mm = 11 cm.
% A slightly taller aspect ratio gives the 2x2 layout more vertical space.
figWidthCM  = 11.0;
figHeightCM = 9.8;

fig = figure( ...
    'Color', 'w', ...
    'Units', 'centimeters', ...
    'Position', [2.0 2.0 figWidthCM figHeightCM], ...
    'PaperUnits', 'centimeters', ...
    'PaperSize', [figWidthCM figHeightCM], ...
    'PaperPosition', [0 0 figWidthCM figHeightCM], ...
    'PaperPositionMode', 'manual');

tl = tiledlayout(fig, 2, 2, ...
    'TileSpacing', 'compact', ...
    'Padding', 'compact');

% No bottom parameter annotation anymore, so almost all canvas is used
% by the four panels.
tl.OuterPosition = [0.065 0.055 0.925 0.925];

%% 3. Panel (a): pre-integration high-tier market
axA = nexttile(tl, 1);
hold(axA, 'on');

vA = linspace(0, pH + 4, nGrid);
gA = linspace(0, 220, nGrid);
[VA, GA] = meshgrid(vA, gA);

gamma0A = SG .* (VA - pH);
gammaFA = (SG - NH) .* (VA - pH - tH);

ZA = classifyCoverage(VA, GA, pH, tH, gamma0A, gammaFA);

hImgA = imagesc(axA, vA, gA, ZA);
set(hImgA, 'AlphaData', 0.78);
set(axA, 'YDir', 'normal');
colormap(axA, regionMap);
caxis(axA, [1 3]);

hA1 = plot(axA, vA, SG .* (vA - pH), ...
    '-', 'Color', boundaryColor, 'LineWidth', lineWidth);
hA2 = plot(axA, vA, (SG - NH) .* (vA - pH - tH), ...
    '--', 'Color', boundaryColor, 'LineWidth', lineWidth);

formatAxes(axA, fontName, axisFontSize, labelFontSize, ...
    [0 pH + 4], [0 220], '$v_h$', '$\gamma_h$');

title(axA, {'(a) Pre-integration', 'high-tier market'}, ...
    'FontName', fontName, 'FontSize', titleFontSize, ...
    'FontWeight', 'bold');

text(axA, 2.20, 122, '$0_h$', 'Interpreter', 'latex', ...
    'FontName', fontName, 'FontSize', regionFontSize, 'FontWeight', 'bold');
text(axA, 3.65, 86, '$P_h$', 'Interpreter', 'latex', ...
    'FontName', fontName, 'FontSize', regionFontSize, 'FontWeight', 'bold');
text(axA, 4.80, 25, '$F_h$', 'Interpreter', 'latex', ...
    'FontName', fontName, 'FontSize', regionFontSize, 'FontWeight', 'bold');

legend(axA, [hA1 hA2], ...
    {'$\gamma_h=S_G(v_h-p_h)$', ...
     '$\gamma_h=(S_G-N_h)(v_h-p_h-t_h)$'}, ...
    'Interpreter', 'latex', ...
    'FontName', fontName, ...
    'FontSize', legendFontSize, ...
    'Location', 'northwest', ...
    'Box', 'on', ...
    'Color', 'white');

%% 4. Panel (b): pre-integration low-tier market
axB = nexttile(tl, 2);
hold(axB, 'on');

vB = linspace(0, pL + 4, nGrid);
gB = linspace(0, 220, nGrid);
[VB, GB] = meshgrid(vB, gB);

gamma0B = SLPre .* (VB - pL);
gammaFB = (SLPre - NL/2) .* (VB - pL - tL/2);

ZB = classifyCoverage(VB, GB, pL, tL/2, gamma0B, gammaFB);

hImgB = imagesc(axB, vB, gB, ZB);
set(hImgB, 'AlphaData', 0.78);
set(axB, 'YDir', 'normal');
colormap(axB, regionMap);
caxis(axB, [1 3]);

hB1 = plot(axB, vB, SLPre .* (vB - pL), ...
    '-', 'Color', boundaryColor, 'LineWidth', lineWidth);
hB2 = plot(axB, vB, (SLPre - NL/2) .* (vB - pL - tL/2), ...
    '--', 'Color', boundaryColor, 'LineWidth', lineWidth);

formatAxes(axB, fontName, axisFontSize, labelFontSize, ...
    [0 pL + 4], [0 220], '$v_l$', '$\gamma_l$');

title(axB, {'(b) Pre-integration', 'low-tier market'}, ...
    'FontName', fontName, 'FontSize', titleFontSize, ...
    'FontWeight', 'bold');

text(axB, 2.35, 122, '$0_l$', 'Interpreter', 'latex', ...
    'FontName', fontName, 'FontSize', regionFontSize, 'FontWeight', 'bold');
text(axB, 3.55, 86, '$P_l$', 'Interpreter', 'latex', ...
    'FontName', fontName, 'FontSize', regionFontSize, 'FontWeight', 'bold');
text(axB, 4.35, 25, '$F_l$', 'Interpreter', 'latex', ...
    'FontName', fontName, 'FontSize', regionFontSize, 'FontWeight', 'bold');

legend(axB, [hB1 hB2], ...
    {'$\gamma_l=S_l^{pre}(v_l-p_l)$', ...
     '$\gamma_l=(S_l^{pre}-N_l/2)(v_l-p_l-t_l/2)$'}, ...
    'Interpreter', 'latex', ...
    'FontName', fontName, ...
    'FontSize', legendFontSize, ...
    'Location', 'northwest', ...
    'Box', 'on', ...
    'Color', 'white');

%% 5. Panel (c): post-integration high-tier market
axC = nexttile(tl, 3);
hold(axC, 'on');

vC = linspace(0, pH + 4, nGrid);
gC = linspace(0, 220, nGrid);
[VC, GC] = meshgrid(vC, gC);

SH0      = SG;
SHEtaBar = (1 - etaBar) * SG;

gamma0C0   = SH0 .* (VC - pH);
gammaFC0   = (SH0 - NH) .* (VC - pH - tH);
gamma0CBar = SHEtaBar .* (vC - pH);
gammaFCBar = (SHEtaBar - NH) .* (vC - pH - tH);

ZC = classifyCoverage(VC, GC, pH, tH, gamma0C0, gammaFC0);

hImgC = imagesc(axC, vC, gC, ZC);
set(hImgC, 'AlphaData', 0.68);
set(axC, 'YDir', 'normal');
colormap(axC, regionMap);
caxis(axC, [1 3]);

hC1 = plot(axC, vC, SH0 .* (vC - pH), ...
    '-', 'Color', eta0Color, 'LineWidth', lineWidth);
hC2 = plot(axC, vC, (SH0 - NH) .* (vC - pH - tH), ...
    '--', 'Color', eta0Color, 'LineWidth', lineWidth);
hC3 = plot(axC, vC, gamma0CBar, ...
    '-', 'Color', etaBarColor, 'LineWidth', lineWidth);
hC4 = plot(axC, vC, gammaFCBar, ...
    '--', 'Color', etaBarColor, 'LineWidth', lineWidth);

drawBoundaryShift(axC, 4.60, ...
    SH0 * (4.60 - pH), SHEtaBar * (4.60 - pH), ...
    etaBarColor, 'down');

drawBoundaryShift(axC, 4.60, ...
    (SH0 - NH) * (4.60 - pH - tH), ...
    (SHEtaBar - NH) * (4.60 - pH - tH), ...
    etaBarColor, 'down');

formatAxes(axC, fontName, axisFontSize, labelFontSize, ...
    [0 pH + 4], [0 220], '$v_h$', '$\gamma_h$');

title(axC, {'(c) Post-integration', 'high-tier market'}, ...
    'FontName', fontName, 'FontSize', titleFontSize, ...
    'FontWeight', 'bold');

text(axC, 3.00, 122, '$0_h$', 'Interpreter', 'latex', ...
    'FontName', fontName, 'FontSize', regionFontSize, 'FontWeight', 'bold');
text(axC, 4.15, 86, '$P_h$', 'Interpreter', 'latex', ...
    'FontName', fontName, 'FontSize', regionFontSize, 'FontWeight', 'bold');
text(axC, 4.80, 25, '$F_h$', 'Interpreter', 'latex', ...
    'FontName', fontName, 'FontSize', regionFontSize, 'FontWeight', 'bold');

text(axC, 5.12, 157, '$\eta=0$', ...
    'Interpreter', 'latex', ...
    'FontName', fontName, ...
    'FontSize', etaFontSize, ...
    'FontWeight', 'bold', ...
    'Color', eta0Color);

text(axC, 4.93, 111, '$\eta=\bar{\eta}=0.30$', ...
    'Interpreter', 'latex', ...
    'FontName', fontName, ...
    'FontSize', etaFontSize, ...
    'FontWeight', 'bold', ...
    'Color', etaBarColor);

% Explicit handles prevent the background image from entering the legend.
% The labels below also correspond to the HIGH-tier boundaries in panel (c).
legend(axC, [hC1 hC2 hC3 hC4], ...
    {'$\eta=0:\ \gamma_h=S_G(v_h-p_h)$', ...
     '$\eta=0:\ \gamma_h=(S_G-N_h)(v_h-p_h-t_h)$', ...
     '$\eta=\bar{\eta}:\ \gamma_h=(1-\eta)S_G(v_h-p_h)$', ...
     '$\eta=\bar{\eta}:\ \gamma_h=((1-\eta)S_G-N_h)(v_h-p_h-t_h)$'}, ...
