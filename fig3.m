clear;
clc;
close all;

%% ==================================================
% 1. Unified calibration
% ==================================================

nTotal = 100;
alpha = 0.30;

nH = alpha * nTotal;
nL = (1 - alpha) * nTotal;

tH = 1;
tL = 1;

sG = 50;      % merged high-tier / GPU pool
sC = 100;     % merged low-tier / CPU pool

pH = 2;
pL = 1.5;

% Fixed-ratio backfilling intensity
etaGrid = 0:0.01:0.80;
nEta = length(etaGrid);

% Numerical tolerance
tol = 1.0e-10;

%% ==================================================
% 2. Representative scenarios
%
% vHSet and vLSet are gross service values.
% Net service values are calculated as:
%
% VH = vH - pH
% VL = vL - pL
% ==================================================

scenarioNames = { ...
    'Moderate sharing', ...
    'Aggressive sharing', ...
    'Low-tier boost' ...
};

% Gross high-tier service values
% Corresponding net values: [1.4, 1.2, 1.2]
vHSet = [3.4, 3.2, 3.2];

% High-tier congestion parameters
gammaHSet = [10, 10, 10];

% Gross low-tier service values
% Corresponding net values: [1.0, 1.1, 1.0]
vLSet = [2.5, 2.6, 2.5];

% Low-tier congestion parameters
gammaLSet = [25, 30, 35];

nScenario = length(scenarioNames);

%% ==================================================
% 3. Parameter validation
% ==================================================

assert(nTotal > 0, ...
    'nTotal must be positive.');

assert(alpha > 0 && alpha < 1, ...
    'alpha must lie strictly between 0 and 1.');

assert(sG > 0 && sC > 0, ...
    'Both capacity pools must be positive.');

assert(tH > 0 && tL > 0, ...
    'Differentiation parameters must be positive.');

assert(all(vHSet > pH), ...
    'Each gross high-tier service value must exceed pH.');

assert(all(vLSet > pL), ...
    'Each gross low-tier service value must exceed pL.');

assert(all(gammaHSet >= 0), ...
    'High-tier congestion parameters must be nonnegative.');

assert(all(gammaLSet >= 0), ...
    'Low-tier congestion parameters must be nonnegative.');

assert(all(etaGrid >= 0 & etaGrid < 1), ...
    'Backfilling intensities must lie in [0,1).');

%% Display scenario calibration

calibrationTable = table( ...
    string(scenarioNames(:)), ...
    vHSet(:), ...
    vHSet(:) - pH, ...
    gammaHSet(:), ...
    vLSet(:), ...
    vLSet(:) - pL, ...
    gammaLSet(:), ...
    'VariableNames', { ...
    'Scenario', ...
    'GrossHighValue', ...
    'NetHighValue', ...
    'GammaHigh', ...
    'GrossLowValue', ...
    'NetLowValue', ...
    'GammaLow' ...
    });

disp(' ');
disp('Representative-scenario calibration:');
disp(calibrationTable);

%% ==================================================
% 4. Preallocate results
% ==================================================

Wh = nan(nScenario, nEta);
Wl = nan(nScenario, nEta);

Profit = zeros(nScenario, nEta);

CSH = zeros(nScenario, nEta);
CSL = zeros(nScenario, nEta);

Welfare = zeros(nScenario, nEta);

DhMat = zeros(nScenario, nEta);
DlMat = zeros(nScenario, nEta);

HighRegime = strings(nScenario, nEta);
LowRegime = strings(nScenario, nEta);

%% ==================================================
% 5. Simulation
% ==================================================

for s = 1:nScenario

    %% Gross service values

    vH = vHSet(s);
    vL = vLSet(s);

    %% Net service values

    VH = vH - pH;
    VL = vL - pL;

    gammaH = gammaHSet(s);
    gammaL = gammaLSet(s);

    for e = 1:nEta

        eta = etaGrid(e);

        %% ------------------------------------------
        % 5.1 Capacity after backfilling
        %% ------------------------------------------

        sH = (1 - eta) * sG;
        sL = sC + eta * sG;

        if sH <= 0
            error(['The high-tier capacity is nonpositive ' ...
                   'at eta = %.4f.'], eta);
        end

        %% ------------------------------------------
        % 5.2 High-tier market equilibrium
        %% ------------------------------------------

        if VH <= 0 || gammaH >= sH * VH

            highReg = "0h";
            dH = 0;

        elseif sH > nH ...
                && VH > tH ...
                && gammaH <= ...
                (sH - nH) * (VH - tH)

            highReg = "Fh";
            dH = nH;

        else

            % Partial-coverage equilibrium:
            %
            % VH - tH*dH/nH - gammaH/(sH-dH) = 0

            AHigh = nH / tH;

            BHigh = sH + AHigh * VH;

            CHigh = AHigh * ...
                (VH * sH - gammaH);

            discHigh = ...
                BHigh^2 - 4 * CHigh;

            if discHigh < -tol

                error(['Negative high-tier discriminant at ' ...
                       'scenario %d and eta = %.4f.'], ...
                       s, eta);

            end

            discHigh = max(discHigh,0);

            rootHigh1 = ...
                (BHigh - sqrt(discHigh)) / 2;

            rootHigh2 = ...
                (BHigh + sqrt(discHigh)) / 2;

            rootsHigh = ...
                [rootHigh1, rootHigh2];

            maximumHighDemand = ...
                min(sH,nH);

            feasibleHigh = rootsHigh( ...
                isfinite(rootsHigh) ...
                & rootsHigh > tol ...
                & rootsHigh < ...
                maximumHighDemand - tol);

            if isempty(feasibleHigh)

                error(['No feasible high-tier partial equilibrium ' ...
                       'at scenario %d and eta = %.4f.'], ...
                       s, eta);

            end

            % Economically relevant smaller root
            dH = min(feasibleHigh);
            highReg = "Ph";

        end

        %% ------------------------------------------
        % 5.3 Low-tier market equilibrium
        %% ------------------------------------------

        if VL <= 0 || gammaL >= sL * VL

            lowReg = "0l";
            dL = 0;

        elseif sL > nL ...
                && VL > tL / 2 ...
                && gammaL <= ...
                (sL - nL) * (VL - tL / 2)

            lowReg = "Fl";
            dL = nL;

        else

            % Partial-coverage equilibrium:
            %
            % VL - tL*dL/(2*nL) - gammaL/(sL-dL) = 0

            ALow = 2 * nL / tL;

            BLow = sL + ALow * VL;

            CLow = ALow * ...
                (VL * sL - gammaL);

            discLow = ...
                BLow^2 - 4 * CLow;

            if discLow < -tol

                error(['Negative low-tier discriminant at ' ...
                       'scenario %d and eta = %.4f.'], ...
                       s, eta);

            end

            discLow = max(discLow,0);

            rootLow1 = ...
                (BLow - sqrt(discLow)) / 2;

            rootLow2 = ...
                (BLow + sqrt(discLow)) / 2;

            rootsLow = ...
                [rootLow1, rootLow2];

            maximumLowDemand = ...
                min(sL,nL);

            feasibleLow = rootsLow( ...
                isfinite(rootsLow) ...
                & rootsLow > tol ...
                & rootsLow < ...
                maximumLowDemand - tol);

            if isempty(feasibleLow)

                error(['No feasible low-tier partial equilibrium ' ...
                       'at scenario %d and eta = %.4f.'], ...
                       s, eta);

            end

            % Economically relevant smaller root
            dL = min(feasibleLow);
            lowReg = "Pl";

        end

        %% ------------------------------------------
        % 5.4 Waiting time
        %% ------------------------------------------

        if sH > dH

            wh = 1 / (sH - dH);

        else

            wh = NaN;

        end

        if sL > dL

            wl = 1 / (sL - dL);

        else

            wl = NaN;

        end

        %% ------------------------------------------
        % 5.5 Platform profit
        %% ------------------------------------------

        profit = ...
            pH * dH + pL * dL;

        %% ------------------------------------------
        % 5.6 High-tier consumer surplus
        %% ------------------------------------------

        if highReg == "0h"

            csh = 0;

        elseif highReg == "Fh"

            csh = nH * ...
                (VH ...
                - gammaH / (sH - nH) ...
                - tH / 2);

        else

            csh = ...
                tH * dH^2 / (2 * nH);

        end

        %% ------------------------------------------
        % 5.7 Low-tier consumer surplus
        %% ------------------------------------------

        if lowReg == "0l"

            csl = 0;

        elseif lowReg == "Fl"

            csl = nL * ...
                (VL ...
                - gammaL / (sL - nL) ...
                - tL / 4);

        else

            csl = ...
                tL * dL^2 / (4 * nL);

        end

        %% Numerical safeguards

        if csh < -tol

            warning(['Negative high-tier consumer surplus at ' ...
                     'scenario %d and eta = %.4f.'], ...
                     s, eta);

        end

        if csl < -tol

            warning(['Negative low-tier consumer surplus at ' ...
                     'scenario %d and eta = %.4f.'], ...
                     s, eta);

        end

        csh = max(csh,0);
        csl = max(csl,0);

        %% ------------------------------------------
        % 5.8 Social welfare
        %% ------------------------------------------

        welfare = ...
            profit + csh + csl;

        %% ------------------------------------------
        % 5.9 Store results
        %% ------------------------------------------

        DhMat(s,e) = dH;
        DlMat(s,e) = dL;

        Wh(s,e) = wh;
        Wl(s,e) = wl;

        Profit(s,e) = profit;

        CSH(s,e) = csh;
        CSL(s,e) = csl;

        Welfare(s,e) = welfare;

        HighRegime(s,e) = highReg;
        LowRegime(s,e) = lowReg;

    end
end

%% ==================================================
% 6. Display market-regime transitions
% ==================================================

disp(' ');
disp('Market-coverage transitions over eta:');

for s = 1:nScenario

    highChange = ...
        [true, ...
         HighRegime(s,2:end) ~= ...
         HighRegime(s,1:end-1)];

    lowChange = ...
        [true, ...
         LowRegime(s,2:end) ~= ...
         LowRegime(s,1:end-1)];

    fprintf('\n%s\n',scenarioNames{s});

    fprintf('  High-tier: ');

    highIndex = find(highChange);

    for k = 1:length(highIndex)

        idx = highIndex(k);

        fprintf('%s at eta = %.2f', ...
            char(HighRegime(s,idx)), ...
            etaGrid(idx));

        if k < length(highIndex)
            fprintf(' -> ');
        end

    end

    fprintf('\n');

    fprintf('  Low-tier:  ');

    lowIndex = find(lowChange);

    for k = 1:length(lowIndex)

        idx = lowIndex(k);

        fprintf('%s at eta = %.2f', ...
            char(LowRegime(s,idx)), ...
            etaGrid(idx));

        if k < length(lowIndex)
            fprintf(' -> ');
        end

    end

    fprintf('\n');

end

